handle_assignment() {
#download unit page, turn text to html2text, find assignment row, pull out values and build json 
	number="$1" 
	
	echo "downloading $UNIT_URL" >&2 #redirects output to standard error 
	curl -s -f -L "$UNIT_URL" -o "$WORK/unit.html"
		#silent, fail if website returns error, L follows redirect, o saves to a file 
		#saved to server_files/unit.html
	if [ $? -ne 0 ]; then 
		error "could not download unit page"
		return 
	fi 

	#split each row into own block - html2text mixes table rows together 
	# turns end of table into ===== line 
	#deletes tags to prevent html2text reading as table 
	#every row start with =====
	#every paragraph = new line 
	sed -e 's#</table>#<hr>#g' \
		-e 's#</*table[^>]*>##g' \
		-e 's#</*thead[^>]*>##g' \
		-e 's#</*tbody[^>]*>##g' \
		-e 's#</tr>##g' \
		-e 's#<tr[^>]*>#<hr>#g' \
		-e 's#<t[dh][^>]*>#<p>#g' \
		-e 's#</t[dh]>#</p>#g' \
        "$WORK/unit.html" > "$WORK/unit_rows.html" 
	html2text -nobs -width 250 "$WORK/unit_rows.html" > "$WORK/unit.txt" 
	#nobs disposes automatic wrapping of long lines 
	#output width = 250 characters 

	title=$(grep "^Assignment [0-9]*$" "$WORK/unit.txt" | tail -n 1) 
	
	grep -A 15 "^$title$" "$WORK/unit.txt" | sed '/^=====/,$d' | grep -v '^ *$' > "$WORK/row.txt" 
	#assignment title + next 15 lines, deletes everything from a line starting =====, removes empty lines 
	cat "$WORK/row.txt" >&2
	
	topic=$(sed -n 2p "$WORK/row.txt" | sed 's/.* - //' | cut -d' ' -f1) 
	#print line 2 only 
	#remove everything up to (including) last matching - 
	points=$(grep '%' "$WORK/row.txt" | head -n 1 | tr -d '%') # delete characters 
	#finds line containing % 
	due=$(grep 'Due date:' "$WORK/row.txt" | sed -e 's/Due date: //' -e 's/ at / /') 
	#remove due date 
	#replace 'at' with space
	
	if [ -z "$title" ] || [ -z "$topic" ] || [ -z "$points" ] || [ -z "$due" ]; then 
	#check if string empty 
		error "could not find assingment details" 
		return 
	fi 

	echo "{\"title\": \"$title\", \"topic\": \"$topic\", \"due_date\": \"$due\" \"points\": $points}" \
		| jq . > "$WORK/assignment.json" 
	cat "$WORK/assignment.json" 
} 

handle_population() {
	curl -s -f -L "$POP_URL" -o "$WORK/STE_1.csv" 
	if [ $? -ne 0 ]; then 
		error "could not download population data" 
		return
	fi 

	header=$(head -n 1 "$WORK/STE_1.csv" | tr -d '\r') 
	row=$(grep "^ERP_P_20," "$WORK/STE_1.csv" | tr -d '\r') 

	#read estimated resident population 
	
	#go through every column 
	rm -f "$WORK/population.txt" 
	column=$(echo "$header" | tr ',' '\n' | wc -l)
	for i in $(seq 1 $column); do 
		year=$(echo "$header" | cut -d',' -f$i) 
		pop=$(echo "$row" | cut -d',' -f$i)
		if echo "$year" | grep -q '^[0-9][0-9][0-9][0-9]$' && [ -n "$pop" ]; then 
			echo "$year,$pop" >> "$WORK/population.txt" 
		fi
	done 

	if [ ! -s "$WORK/population.txt" ]; then
		error "no population numbers found in the csv" 
		return 
	fi
	echo "Latest NSW population: $(tail -n 1 "$WORK/population.txt")" >&2 
#the following python code was generated by ChatGPT (acknowledgements in README.md)
	rm -f "$WORK/population.png"
	python3 - "$WORK/population.txt" "$WORK/population.png" <<'PYTHON'
