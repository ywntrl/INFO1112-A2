} 

#where am i? 
handle_poi() { 
	#read coordinates using grep 
	if echo "$1" | grep -q -E '^-?[0-9.]+,-?[0-9.]+$'; then 
	# -?: Optional negative sign.
	# [0-9.]+: One or more digits or decimal points.
		lat=$(echo "$1" | cut -d',' -f1) 
		lon=$(echo "$1" | cut -d',' -f2) 
	else 
	
	#curl - look up POI name for coordinates 
		name=$(echo "$1" | tr 'a-z' 'A-Z') 
		curl -s -f -G \
			--data-urlencode "where=poiname='$name'" \
			--data-urlencode "outFields=poiname" \
			--data-urlencode "returnGeometry=true" \
			--data-urlencode "f=json" \
			"$POI_URL" -o "$WORK/poi.json" 
		#specifies search condition 
		#requests POI name field 
		#API return geometric coordinates + name
		#json response 
		#send request to nsw poi 
		
		lat=$(jq -r '.features[0].geometry.y // empty' "$WORK/poi.json" 2>/dev/null) 
		lon=$(jq -r '.features[0].geometry.x // empty' "$WORK/poi.json" 2>/dev/null) 
		
		#error if no POI found for given name/coordinates 
		if [ -z "$lat" ]; then 
			error "no POI called '$1' was found" 
			return 
		fi 
	fi 
	echo "where am I? $1 is at $lat, $lon" >&2 
	

	#curl - every POI within 500m of given point 
	curl -s -f -G \
		--data-urlencode "geometry=$lon,$lat" \
		--data-urlencode "geometryType=esriGeometryPoint" \
		--data-urlencode "inSR=4283" \
		--data-urlencode "distance=$RADIUS" \
		--data-urlencode "units=esriSRUnit_Meter" \
		--data-urlencode "outFields=poiname,poitype" \
		--data-urlencode "f=json" \
		"$POI_URL" -o "$WORK/around.json"
	if [ $? -ne 0 ]; then
		error "could not reach the NSW POI API"
		return
	fi

	#list of {name, type} to neighbours.json
	jq '[.features[] | {name: .attributes.poiname, type: .attributes.poitype}]' \
		"$WORK/around.json" > "$WORK/neighbours.json"
	cat "$WORK/neighbours.json" >&2
	cat "$WORK/neighbours.json"
}

